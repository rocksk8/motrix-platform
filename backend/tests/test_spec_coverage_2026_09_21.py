_INLINE_MARKS = re.compile(r"(?<=[A-Za-z0-9])(?:\*\*|~~|\*|`|_)+(?=[A-Za-z0-9])")


def strip_inline_marks(text):
    """把**夾在英數字之間**的行內標記拿掉；其餘一字不動。"""
    return _INLINE_MARKS.sub("", text)


def _scope_sections():
    """`SCOPE.md` 的三個區塊 → 各自的編號集合。

    ⚠️ 用 `## ` 標題切段，而**不是**靠段落順序 ——
    ☠️ 靠順序的話，A 在中間插一段說明就會讓整份解析錯位，
    🔑 而錯位的樣子是「某一區忽然空了」，那與「清完了」長得一樣。

    ## ⚠️ 只讀**程式碼圍欄裡**的編號，而我第一版連散文也讀

    ☠️ 結果我解析出 **68 個**而 A 說是 **64 個** —— 多出來的四個來自
    `THIS` 區塊裡的說明文字（它提到了 `G1`、`T1` 這些別節的編號）。
    🔑 而那四個假陽性讓「跳號偵測」報出 17 個不存在的洞
    （`BK9`／`G2`–`G11`／`T2`–`T7`）——
    📌 **一份清單混了「項目」與「談論項目的話」，解析器分不出來。**
    ⇒ 圍欄是那條界線，而它本來就在那裡，我只是沒有用它。

    ## ⚠️ 每個 key 只認**第一個**出現的標題（A-2 2026-09-23 抓到）

    ☠️ 原本「標題字面含 key 就判給那個 key」——而 A 的筆記段標題常常
    同時提到兩個字（例如「把 5 個從 `THIS` 搬到 `NEXT`」），取第一個
    命中 ⇒ 一篇「把 X 移出 THIS」的筆記反而把 X 判回了 `THIS`
    （見 `test_scope_sections_are_mutually_exclusive`，修好前
    `THIS ∩ NEXT` 有 11 個、`NEXT ∩ EXEMPT` 還有 1 個）。
    ⇒ 每個 key 一旦被用過就從候選裡拿掉：真正的三個區塊標題
    （`THIS`／`NEXT`／`EXEMPT` 各一次）之後，其餘所有 `## ` 一律判
    `current = None`，筆記段的內容不再被算進任何區塊。
    """
    sections = {"THIS": set(), "NEXT": set(), "EXEMPT": set()}
    _parse_scope(SCOPE.read_text(encoding="utf-8"), sections)
    for p in _module_specs():
        # 模組 SPEC.md 的 `## 範圍` 底下用 `### THIS／NEXT／EXEMPT` ⇒ 升一級後用同一套解析
        block = _md_section(p.read_text(encoding="utf-8"), "範圍")
        _parse_scope("\n".join(("## " + l[4:]) if l.startswith("### ") else l for l in block.splitlines()),
                     sections)
    return sections


def _parse_scope(text, sections):
    """一份範圍文字 → 併入 sections（規則見 `_scope_sections`）。"""
    current = None
    in_block = False
    seen = set()
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            current = None
            in_block = False
            for key in sections:
                if key not in seen and key in stripped:
                    current = key
                    seen.add(key)
                    break
            continue
        if stripped.startswith("```"):
            in_block = not in_block
            continue
        if current and in_block and stripped:
            for num in _SCOPE_NUM.findall(strip_inline_marks(line)):
                sections[current].add(num.upper())

