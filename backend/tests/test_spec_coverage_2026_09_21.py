_SCOPE_NUM = re.compile(r"\b([A-Z]{1,2}\d{1,2}[a-z]?)\b")

#: 🔴 `MD1(b)`：**比對前把行內標記剝掉**（A `§118`／`§119`）。
#: ```
#: 'UI**10** DB1'   舊 => ['DB1']      ⇒ **UI10 消失，而不會有任何錯誤**
