def _declared_where():
    """每個編號 → 它在規格裡被宣告的行號清單。"""
    text = SPEC.read_text(encoding="utf-8")
    where = defaultdict(list)
    for rx in (_DECLARED_BULLET, _DECLARED_TABLE):
        for m in rx.finditer(text):
            where[m.group(1).upper()].append(text.count("\n", 0, m.start()) + 1)
    return where


def _declared():
    return set(_declared_where())


def _implemented_where():
    """每個編號 → 寫著它的測試檔清單。"""
    where = defaultdict(set)
    for path in sorted(TESTS.glob("test_*.py")):
        for m in _IMPLEMENTED.finditer(path.read_text(encoding="utf-8")):
            where[m.group(1).upper()].add(path.name)
    return where


def _implemented():
    """**已實作**的編號 —— 撞名的不算。

    ⚠️ 撞名有兩種，兩種都讓這支守門失去分辨能力：
    ① 規格裡同一個編號宣告兩次（不同節各自從 T1 重編）
    ② 同一個編號出現在兩個不相干的測試檔裡
    ⇒ 兩種都**不給信用**，改由 `AMBIGUOUS_ACK` 明文記錄。
    """
    where = _implemented_where()
    ambiguous = {n for n, files in where.items() if len(files) > 1}
    ambiguous |= {n for n, lines in _declared_where().items() if len(lines) > 1}
    return set(where) - ambiguous - set(MISCREDITED)


