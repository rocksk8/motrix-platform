    # `MISCREDITED` 的定義就是「規格有、測試也有，但那個測試是別的東西」
    # ⇒ 兩邊有任何一邊沒有，這一列就失去意義。
    ghost_mis = sorted(n for n in MISCREDITED
                       if n not in _declared() or n not in implemented)
