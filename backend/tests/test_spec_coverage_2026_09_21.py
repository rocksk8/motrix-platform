def _headings_to_ignore():
    """哪些「有編號的標題」**不算**一次新的宣告。兩種：

    ```
    ① 群組標題   `### FX1 ·` 底下有 FX1a／FX1b  ⇒ FX1 是群組，不是條件
    ② 同號重述   `### A16 ·` 而 A16 已經是一條條列 ⇒ 那是那一條的節標題
    ```
    ⚠️ ②少了的話，`A16`／`G10` 會被當成「宣告兩次」而掉進 `AMBIGUOUS`，
    ☠️ 而它們其實只被宣告過一次 —— **守門會因為自己看重了而失去分辨能力。**
    📌 ①的判準是「有沒有子編號」，**不是「我覺得它像不像群組」**。
    """
    text = SPEC.read_text(encoding="utf-8")
    leaf = set()
    for rx in (_DECLARED_BULLET, _DECLARED_TABLE):
        leaf |= {m.group(1).upper() for m in rx.finditer(text)}
    ignore = set()
    for m in _DECLARED_HEADING.finditer(text):
        num = m.group(1).upper()
        if num in leaf:
            ignore.add(num)                                   # ② 同號重述
        elif any(d != num and d.startswith(num) and len(d) > len(num)
                 for d in leaf):
            ignore.add(num)                                   # ① 群組標題
    return ignore


def _declared_where():
    """每個編號 → 它在規格裡被宣告的行號清單。"""
    text = SPEC.read_text(encoding="utf-8")
    where = defaultdict(list)
    ignore = _headings_to_ignore()
    for rx in (_DECLARED_BULLET, _DECLARED_TABLE, _DECLARED_HEADING):
        for m in rx.finditer(text):
            num = m.group(1).upper()
            if rx is _DECLARED_HEADING and num in ignore:
                continue
            where[num].append(text.count("\n", 0, m.start()) + 1)
    return where


def _declared():
    return set(_declared_where())


def _implemented_where():
    """每個編號 → 寫著它的測試檔清單。"""
    where = defaultdict(set)
    for path in sorted(TESTS.glob("test_*.py")):
        for m in _IMPLEMENTED.finditer(path.read_text(encoding="utf-8")):
            where[m.group(1).upper()].add(path.name)
    return where


def _implemented():
    """**已實作**的編號 —— 撞名的不算。

    ⚠️ 撞名有兩種，兩種都讓這支守門失去分辨能力：
    ① 規格裡同一個編號宣告兩次（不同節各自從 T1 重編）
    ② 同一個編號出現在兩個不相干的測試檔裡
    ⇒ 兩種都**不給信用**，改由 `AMBIGUOUS_ACK` 明文記錄。
    """
    where = _implemented_where()
    ambiguous = {n for n, files in where.items() if len(files) > 1}
    ambiguous |= {n for n, lines in _declared_where().items() if len(lines) > 1}
    return set(where) - ambiguous - set(MISCREDITED)


def test_the_holding_pen_cannot_become_a_place_things_rot():
    """🔴🔴 **`UNTRIAGED_HEADINGS` 是暫存欄，不可以變成第五種「已處理」。**

    ## ☠️ 它跟另外三張表的差別

    `EXEMPT`／`PENDING`／`AMBIGUOUS_ACK` 的每一列都答完了問題。
    **這一欄沒有** —— 它的意思只是「守門今天第一次看見它，而還沒有人分流」。
    🔑 〈守門被拿掉≠規則被解除〉：
    **我把它們寫進一張表讓守門變綠，那不等於它們被處理了。**

    ## 📌 所以這一題守三件事

    ```
    ① 每一條都還在規格裡      ← 幽靈列（規格改了而表沒改）會佔著「已處理」的位置
    ② 沒有一條已經寫了題      ← 寫了就該搬進正軌，不該留在暫存欄
    ③ 沒有一條同時在別張表裡  ← 兩處記載會讓移除其中一處看起來沒有影響
    ```
    ⚠️ ②是這一題最重要的一半：**一條被做完卻留在暫存欄的項目，
    會讓這張表看起來永遠都有那麼多欠帳**，而那正是〈量測比變化慢〉。
    """
    declared = _declared()
    ghosts = sorted(set(UNTRIAGED_HEADINGS) - declared)
    assert not ghosts, (
        "這些還在暫存欄裡，而規格已經不宣告它們了：\n  " + "\n  ".join(ghosts)
        + "\n⇒ 刪掉這幾列。**一張表的雜訊也會被讀成決定。**"
    )

    done = sorted(set(UNTRIAGED_HEADINGS) & _implemented())
    assert not done, (
        "這些已經有題了，卻還留在暫存欄：\n  " + "\n  ".join(done)
        + "\n⇒ 搬出去。留著會讓欠帳看起來比實際多。"
    )

    both = sorted(set(UNTRIAGED_HEADINGS)
                  & (set(EXEMPT) | set(PENDING) | AMBIGUOUS_ACK))
    assert not both, (
        "這些同時記在暫存欄與另一張表裡：\n  " + "\n  ".join(both)
        + "\n⇒ 只留分流後的那一張。"
    )


