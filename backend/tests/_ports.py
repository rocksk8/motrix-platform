"""挑一個瀏覽器願意連的空閒埠（e2e 的 `live_server` 專用）。

## 這支的由來：**同一個 bug 咬了兩次，中間隔了十天**

**2026-09-11**：`test_e2e_passkey` 抽到 **1723（PPTP）**，`page.goto` 回
`net::ERR_UNSAFE_PORT`。當時寫了一支 `_pick_browser_safe_port()` 修好，
**而且 docstring 裡已經有完整診斷** —— 包含 Chromium 黑名單、`netsh` 動態埠範圍、
以及「這種失敗是間歇性的，錯誤訊息完全看不出跟埠號有關」。

**2026-09-21**：第 5 輪的⑥紅了 `test_e2e_material_orders`，抽到 **2049（NFS）**，
一模一樣的錯誤。

⚠️ **修法早就存在，只是待在 21 個檔的其中 1 個裡。**

> 🔑 **修好一個實例，不等於認得那個模式。**
> 而這一次的載體是**十天前一份寫得很好的診斷** —— 它救了那一個檔，
> 沒有救其餘二十個。**把結論寫進註解，不等於把它變成守門。**

## Chromium 為什麼拒連

它內建一份約 80 個埠的黑名單（`net/base/port_util.cc` 的 `kRestrictedPorts`），
對名單上的埠**一律拒絕連線，跟伺服器有沒有起來完全無關**。
名單裡最大的是 **10080**。

## 為什麼不讓 OS 用 `port=0` 抽

```
netsh int ipv4 show dynamicport tcp
  Start Port : 1025          ← Windows 預設是 49152
  Number     : 64511
```

這台機器的動態埠範圍被放寬過，**涵蓋了 17 個黑名單埠**（其餘 60 幾個都 < 1025）。
單次抽中的機率只有 **0.026%** —— 所以它**偶發**，而偶發正是最難歸因的那種。

⚠️ **換一台預設設定的機器（49152 起），這個 bug 就完全消失** ——
**而那會讓下一個人更確信「是環境問題」。**
那支測試自己的註解本來就寫著「全套跑的時候這支偶發逾時」：
**有人注意到了，然後歸因成逾時。它不是逾時，是連都沒連上。**

> **偶發的失敗最容易被歸因成「環境不穩」，而那個解釋會停止調查。**

⇒ 所以**不依賴動態埠範圍**，直接在 20000 以上自己挑（黑名單最大是 10080）。
這個做法**不管機器怎麼設定都成立**。

⚠️ **不要只排除 2049。** 下次抽到 6000／6667 一樣紅，**而且那時更難聯想** ——
因為「2049 那次修好了」會讓人以為這一類已經處理過。
"""
import random
import socket

# Chromium 的受限埠清單。
# 出處：chromium/src `net/base/port_util.cc` 的 `kRestrictedPorts`。
# ⚠️ 這是**照抄來源**的清單，不是我們自己挑的「看起來危險的埠」——
#    下一個人不必判斷哪些該留，要更新就去對那份原始碼。
CHROMIUM_RESTRICTED_PORTS = frozenset({
    1, 7, 9, 11, 13, 15, 17, 19, 20, 21, 22, 23, 25, 37, 42, 43, 53, 69, 77, 79,
    87, 95, 101, 102, 103, 104, 109, 110, 111, 113, 115, 117, 119, 123, 135, 137,
    139, 143, 161, 179, 389, 427, 465, 512, 513, 514, 515, 526, 530, 531, 532,
    540, 548, 554, 556, 563, 587, 601, 636, 989, 990, 993, 995, 1719, 1720, 1723,
    2049, 3659, 4045, 5060, 5061, 6000, 6566, 6665, 6666, 6667, 6668, 6669, 6697,
    10080,
})

# 黑名單最大是 10080，所以 20000 以上一定安全；上限留給系統。
SAFE_PORT_LO, SAFE_PORT_HI = 20000, 60000
_MAX_TRIES = 200


def free_safe_port() -> int:
    """回一個目前空閒、且瀏覽器不會拒連的埠。

    ⚠️ **重試寫在這一層**，不交給呼叫端的啟動等待迴圈。交出去的話，
    失敗會表現成「**啟動慢**」而不是「**埠被搶走**」—— 又是歸因錯誤那一族。

    ⚠️ 殘留風險（誠實標註）：bind 拿到空閒埠後會關閉 socket，呼叫端再 bind 一次，
    中間有**極小的競爭窗口** —— **那是原本 `port=0` 沒有的**。
    引進一個新風險去修一個舊 bug，要說出來。窗口極短，呼叫端也有啟動重試。
    """
    for _ in range(_MAX_TRIES):
        port = random.randint(SAFE_PORT_LO, SAFE_PORT_HI)
        # 這道檢查在目前的區間裡**永遠為真**（黑名單最大 10080 < 20000）。
        # 留著是因為它釘住「區間與黑名單的關係」——有人把 SAFE_PORT_LO 調低時，
        # `test_ports_helper` 會紅。**守門要守的是未來的改動，不是現在的狀態。**
        if port in CHROMIUM_RESTRICTED_PORTS:
            continue
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            try:
                sock.bind(("127.0.0.1", port))
            except OSError:
                continue          # 已被占用，換一個
        return port
    raise RuntimeError(
        "在 %d-%d 之間試了 %d 次都綁不到埠" % (SAFE_PORT_LO, SAFE_PORT_HI, _MAX_TRIES)
    )
