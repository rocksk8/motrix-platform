"""把「現在是幾點」釘住 —— 需要它的測試共用這一支。

## 為什麼要有這個家

§3j 把抓取從「每日一次」改成「每個時段一次」（預設 9,12,15,18）。
⇒ **任何驗「連續兩次只抓一次」的測試，都變成時間相依的。**

☠️ 而它壞掉的樣子最貴：測試若剛好在 **8:59 跑第一次、9:00 跑第二次**
（或 11:59/12:00、14:59/15:00、17:59/18:00）⇒ 跨時段 ⇒ 抓兩次 ⇒ 紅。
🔴 **一天四個這種邊界，而且全部落在上班時間。**
⇒ 失敗率低、無法重現、**而且看起來像真的有 bug**。

> 🔑 **偶爾紅的綠燈比紅燈貴**：紅燈會被修，偶爾紅的綠燈會被重跑一次然後忘掉。

需要它的有**四個**地方（S4／D13／9c／§3j 那一批），所以它住在這裡而不是被抄四份 ——
**同一天我已經因為「抄而不是收」付過兩次代價**（21 個 e2e 檔各自挑埠、
四個 harness 各自 spawn 子行程）。**修好一個實例不等於認得那個模式。**
"""
from datetime import datetime


def freeze_slot(monkeypatch, mod, hour=9):
    """把 `mod.now_dt()` 釘在今天的 `hour` 點。

    ⚠️ **刻意不做優雅降級**（`hasattr` 就跳過）：`now_dt` 不存在時就該紅。
    🔑 **「這個接縫還沒做好」與「這個行為是對的」不可以長得一樣** ——
    而優雅降級正是讓它們長得一樣的那個動作。

    ⚠️ 也**刻意不 patch `current_slot()`**：那一支內部要讀設定，
    patch 掉它就把「有沒有查設定」這件事一起 patch 掉了。
    換掉最底層碰系統時鐘的那個，讓上層自己去推導。
    """
    if not hasattr(mod, "now_dt"):
        raise AssertionError(
            "`%s` 缺少 `now_dt()` —— §3j 要求把時間來源抽成模組屬性"
            "（形狀比照既有的 `today()`，它的 docstring 就寫著"
            "「存在的理由是讓測試換得掉」）。\n"
            "沒有它，這一題會在一天四個時段邊界上偶爾紅，"
            "而那種紅看起來像真的有 bug。" % mod.__name__
        )
    fixed = datetime.combine(mod.today(), datetime.min.time()).replace(hour=hour)
    monkeypatch.setattr(mod, "now_dt", lambda: fixed)
    return fixed
