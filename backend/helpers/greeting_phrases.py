_BRACE = re.compile(r"\{([^{}]*)\}")


def check_phrase(text) -> str:
    """回問題描述（白話），合法回 ''。"""
    if not isinstance(text, str):
        return "句子必須是文字"
    s = text.strip()
    if not s:
        return "句子不可以是空白"
    if len(s) > MAX_LEN:
        return "每一句最多 %d 個字（目前 %d 個字）" % (MAX_LEN, len(s))
    if _BAD_CHARS.search(s):
        return "句子不可以含換行或 < > 符號"
    for m in _BRACE.finditer(s):
        if m.group(1) not in PLACEHOLDERS:
            return "句子裡的 {%s} 不認得；可以用的只有 {name}、{pending}、{days}" % m.group(1)
    if s.count("{") != s.count("}") or re.search(r"\{[^{}]*$", s) or re.search(r"^[^{}]*\}", s):
        return "句子裡的大括號 { } 沒有成對"
    for w in _BANNED:
        if w in s:
            return "句子裡有「%s」——問候語不可以拿年齡、性別、外表或工作表現開玩笑" % w
    return ""


